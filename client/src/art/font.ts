/** Curly quotes and the en dash render as their ASCII counterparts. */
const ALIASES: Record<string, string> = {
  '’': "'",
  '‘': "'",
  '“': '"',
  '”': '"',
  '–': '-',
};

/** Every character the atlas can draw, in atlas order (RetroFont maps them sequentially). */
export const FONT_CHARS = [...Object.keys(G), ...Object.keys(ALIASES)].join('');
export const FONT_COLUMNS = 16;

function glyphRows(ch: string): readonly string[] {
  const rows = G[ch] ?? G[ALIASES[ch] ?? '?'];
  if (!rows) {
    throw new Error(`font: no glyph for ${JSON.stringify(ch)}`);
  }
  return rows;
}

/** Validates every glyph's shape; throws on typos so tests catch broken art. */
export function validateFont(): void {
  for (const [ch, rows] of Object.entries(G)) {
    if (rows.length > INK_ROWS) {
      throw new Error(`font: ${JSON.stringify(ch)} has ${rows.length} rows (max ${INK_ROWS})`);
    }
    for (const row of rows) {
      if (row.length !== 5 && !(ch === '—' && row.length === 6)) {
        throw new Error(`font: ${JSON.stringify(ch)} row "${row}" is ${row.length} wide`);
      }
      if (!/^[#.]+$/.test(row)) {
        throw new Error(`font: ${JSON.stringify(ch)} row "${row}" has stray characters`);
      }
    }
  }
}

/** Bakes the whole font into one atlas in `rgb` (one atlas per text color keeps every renderer exact). */
export function fontAtlas(rgb: number): Bitmap {
  const chars = [...FONT_CHARS];
  const rows = Math.ceil(chars.length / FONT_COLUMNS);
  const atlas = new Bitmap(FONT_COLUMNS * GLYPH_W, rows * GLYPH_H);
  chars.forEach((ch, index) => {
    const ox = (index % FONT_COLUMNS) * GLYPH_W;
    const oy = Math.floor(index / FONT_COLUMNS) * GLYPH_H;
    glyphRows(ch).forEach((row, y) => {
      for (let x = 0; x < row.length; x += 1) {
        if (row[x] === '#') {
          atlas.set(ox + x, oy + y, rgb);
        }
      }
    });
  });
  return atlas;
}

/** Width in pixels of the longest line of `text` at font scale 1. */
export function measureText(text: string): number {
  return Math.max(0, ...text.split('\n').map((line) => [...line].length * GLYPH_W)) - (text.length > 0 ? 1 : 0);
}
